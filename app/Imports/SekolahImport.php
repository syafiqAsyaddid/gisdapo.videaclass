<?php

namespace App\Imports;

use App\Models\Jenjang;
use App\Models\KategoriSekolah;
use App\Models\OldUser;
use App\Models\Sekolah;
use App\Models\User;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;
use Maatwebsite\Excel\Concerns\ToCollection;
use Maatwebsite\Excel\Concerns\WithHeadingRow;

ini_set('max_execution_time', '3000');

class SekolahImport implements ToCollection, WithHeadingRow
{

    protected $kecamatan;

    public function __construct(int $kecamatan)
    {
        $this->kecamatan = $kecamatan;
    }

    public function collection(Collection $rows)
    {
        // Cache Jenjang and Kategori to avoid repeated DB queries
        // Use lower case keys for case-insensitive matching
        $jenjangMap = Jenjang::all()->pluck('id', 'nama_jenjang')->mapWithKeys(function ($item, $key) {
             return [strtolower($key) => $item];
        });
        
        // Add common abbreviations mapping to full names
        $jenjangAbbreviations = [
            'tk' => 'taman kanak-kanak',
            'paud' => 'pendidikan anak usia dini',
            'sd' => 'sekolah dasar',
            'smp' => 'sekolah menengah pertama',
            'sma' => 'sekolah menengah atas',
            'smk' => 'sekolah menengah kejuruan',
            'slb' => 'sekolah luar biasa',
        ];
        
        $kategoriMap = KategoriSekolah::all()->pluck('id', 'kategori_sekolah')->mapWithKeys(function ($item, $key) {
             return [strtolower($key) => $item];
        });

        foreach ($rows as $row) {
            
            // Normalize Excel data
            $npsn = isset($row['npsn']) ? trim($row['npsn']) : null;
            $nama = isset($row['nama_sekolah']) ? trim($row['nama_sekolah']) : null;
            $nss = isset($row['nss']) ? trim($row['nss']) : null;
            
            // Handle Jenjang Lookup - first check abbreviation, then direct match
            $jenjangNama = isset($row['jenjang']) ? trim(strtolower($row['jenjang'])) : '';
            
            // If it's an abbreviation, convert to full name
            if (isset($jenjangAbbreviations[$jenjangNama])) {
                $jenjangNama = $jenjangAbbreviations[$jenjangNama];
            }
            
            $jenjangId = $jenjangMap[$jenjangNama] ?? null;

            // Handle Kategori Lookup (column: Kategori (Swasta/Negeri))
            // The heading row processor typically converts "Kategori (Swasta/Negeri)" to something like "kategori_swastanegeri"
            // We need to be careful with the exact slug generated by Laravel Excel. 
            // Usually it converts special chars to _ and lowercase. 
            // "Kategori (Swasta/Negeri)" -> "kategori_swastanegeri" or similar.
            // Let's assume standard slug or check multiple keys if unsure. 
           
            $kategoriNama = '';
            // Try standard slug
            if (isset($row['kategori_swastanegeri'])) {
                $kategoriNama = trim(strtolower($row['kategori_swastanegeri']));
            } elseif (isset($row['kategori'])) {
                 $kategoriNama = trim(strtolower($row['kategori']));
            }

            $kategoriId = $kategoriMap[$kategoriNama] ?? null;

            // If critical data is missing, skip row
            if (!$npsn || !$nama) {
                continue; 
            }

            $cek = Sekolah::where('npsn', $npsn)->first();
            
            if ($cek){
             $cek->update([
                 'nama' => $nama,
                //  'alamat' => $row['alamat'], // Not in new spec
                 'nss' => $nss,
                 'kecamatan_id' => $this->kecamatan,
                 'jenjang_id' => $jenjangId,
                 'kategori_sekolah_id' => $kategoriId,
             ]);
            } else {
                $sekolah = Sekolah::create([
                    'kecamatan_id' => $this->kecamatan,
                    'npsn' => $npsn,
                    'nss' => $nss,
                    'nama' => $nama,
                    // 'alamat' => $row['alamat'], // Not in new spec
                    'jenjang_id' => $jenjangId,
                    'kategori_sekolah_id' => $kategoriId,
                ]);

                $password1 = Str::random(8); // Operator default password
                $password2 = Str::random(8); // Kepsek default password

                $userOperator = User::create([
                    'username' => 'operator' . $sekolah->npsn,
                    'password' => Hash::make($password1),
                    'sekolah_id' => $sekolah->id,
                    'hak_akses_id' => 1,
                    'remember_token' => Str::random(10)
                ]);

                $userKepsek = User::create([
                    'username' => 'kepsek' . $sekolah->npsn,
                    'password' => Hash::make($password2),
                    'sekolah_id' => $sekolah->id,
                    'hak_akses_id' => 2,
                    'remember_token' => Str::random(10)
                ]);

                OldUser::create([
                    'users_id' => $userOperator->id,
                    'username' => $userOperator->username,
                    'first_password' => $password1
                ]);

                OldUser::create([
                    'users_id' => $userKepsek->id,
                    'username' => $userKepsek->username,
                    'first_password' => $password2
                ]);
            }
        }
    }
}
